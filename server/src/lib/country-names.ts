const regionDisplay = (() => {
    try {
        return new Intl.DisplayNames(['zh-CN'], { type: 'region' })
    } catch {
        return null
    }
})()

/** 国家代码（两位字母）→ 中文短名；非法代码返回 null。 */
export function countryName(code: string | null | undefined): string | null {
    const c = String(code || '').trim().toUpperCase()
    if (!/^[A-Z]{2}$/.test(c)) return null

    const short = SHORT_REGION_NAMES[c]
    if (short) return short

    try {
        const intl = regionDisplay?.of(c)
        if (!intl) return null
        const alias = LONG_NAME_ALIASES.find(([long]) => long === intl)
        return alias ? alias[1] : intl
    } catch {
        return null
    }
}

/** 把已有文本里的长地区名替换成短名（用于历史券的 item_name 等存量数据）。 */
export function shortenRegionText(text: string): string {
    let out = String(text || '')
    for (const [long, short] of LONG_NAME_ALIASES) {
        if (long !== short && out.includes(long)) {
            out = out.split(long).join(short)
        }
    }
    return out
}
